import type { SiftStore } from "../store/db.ts";
import type { ThemeState } from "../types.ts";

/**
 * The eval-loop export (OVERVIEW.md §3.4).
 *
 * A failure theme becomes a regression test seeded from the real traces that
 * formed it: discovery → known failure → regression test → resolved. That loop
 * is the product; the clusters are just the intake.
 *
 * It is also the validation story for the whole tool. "Are these themes real?"
 * has an answer that is not a vibe check: a theme is real when a test derived
 * from it catches a regression, or when fixing it moves a metric.
 */

export interface EvalCase {
  themeId: string;
  themeLabel: string;
  /** the request to replay — the user's opening ask, not the whole trace */
  input: string;
  /** the facet summary that put this trace in the theme */
  symptom: string;
  sourceTraceId: string;
  version?: string;
  meta: Record<string, unknown>;
}

export interface EvalExport {
  themeId: string;
  facet: string;
  label: string;
  description: string;
  state: ThemeState;
  memberCount: number;
  scorerPrompt: string;
  cases: EvalCase[];
  warnings: string[];
}

export interface ExportOptions {
  maxCases?: number;
}

export function exportTheme(store: SiftStore, themeId: string, opts: ExportOptions = {}): EvalExport {
  const theme = store.getTheme(themeId);
  if (!theme) throw new Error(`no such theme: ${themeId}`);

  const maxCases = opts.maxCases ?? 10;
  const traces = store.tracesForTheme(theme.id, maxCases);

  const cases: EvalCase[] = traces.map((trace) => {
    const summary = store.getSummary(trace.id, theme.facet);
    const c: EvalCase = {
      themeId: theme.id,
      themeLabel: theme.label,
      input: extractInput(trace.text),
      symptom: summary?.summary ?? "",
      sourceTraceId: trace.id,
      meta: trace.meta,
    };
    if (trace.version) c.version = trace.version;
    return c;
  });

  const warnings: string[] = [];
  if (cases.length === 0) {
    warnings.push(`theme ${theme.id} has no traces assigned yet, so this export contains no fixtures`);
  }

  return {
    themeId: theme.id,
    facet: theme.facet,
    label: theme.label,
    description: theme.description,
    state: theme.state,
    memberCount: theme.memberCount,
    scorerPrompt: buildScorerPrompt(theme.facet, theme.label, theme.description, cases),
    cases,
    warnings,
  };
}

/**
 * The reproduction input: the first thing the user actually asked for.
 *
 * Replaying the whole rendered trace would be circular — the agent's own
 * previous output would be handed back to it as the prompt — so this digs out
 * the opening request and only falls back to the head of the trace when the
 * span attributes carried nothing recognisable.
 */
export function extractInput(text: string, maxChars = 4000): string {
  const lines = text.split("\n");
  for (const line of lines) {
    for (const prefix of ["input: ", "user: "]) {
      if (line.startsWith(prefix)) {
        const value = line.slice(prefix.length).trim();
        if (value.length > 0) return value.slice(0, maxChars);
      }
    }
  }
  return text.slice(0, maxChars).trim();
}

function buildScorerPrompt(facet: string, label: string, description: string, cases: EvalCase[]): string {
  const symptoms = [...new Set(cases.map((c) => c.symptom).filter(Boolean))].slice(0, 5);
  const lines: string[] = ["You are scoring an AI agent trace for one known failure mode.", ""];

  lines.push(`Failure mode (${facet}): ${label}`);
  if (description) lines.push(`Description: ${description}`);
  if (symptoms.length > 0) {
    lines.push("", "Traces in this group were summarized as:", ...symptoms.map((s) => `- ${s}`));
  }

  // Stated in both directions on purpose: a convention where 0 and 1 are
  // ambiguous silently inverts every eval built on top of this scorer.
  lines.push(
    "",
    "Scoring: 1 if the trace does NOT exhibit this failure mode (the agent behaved well).",
    "Scoring: 0 if the trace exhibits this failure mode.",
    "",
    'Respond with ONLY JSON: {"score": 0 or 1, "reason": "..."}',
  );
  return lines.join("\n");
}

/** `SIFT-14` -> `sift14`, always a valid JS identifier. */
export function scorerIdentifier(themeId: string): string {
  const cleaned = themeId.toLowerCase().replace(/[^a-z0-9]/g, "");
  return /^[0-9]/.test(cleaned) ? `t${cleaned}` : cleaned || "theme";
}

/** Drop-in Mastra custom scorer plus the fixtures that motivated it. */
export function toMastraScorerModule(exp: EvalExport): string {
  const id = scorerIdentifier(exp.themeId);
  return `// Generated by sift from theme ${exp.themeId}: ${exp.label}
// ${exp.memberCount} traces matched this theme (facet: ${exp.facet}, state: ${exp.state}).
// Drop into your Mastra project's scorers and wire it into your eval run.
import { createScorer } from "@mastra/evals";

export const ${id}Scorer = createScorer({
  name: ${JSON.stringify(`sift: ${exp.label}`)},
  description: ${JSON.stringify(exp.description)},
  judge: {
    instructions: ${JSON.stringify(exp.scorerPrompt)},
  },
});

export const ${id}Cases = ${JSON.stringify(exp.cases, null, 2)};
`;
}

/**
 * The same content with no dependencies at all, so it can be imported by any
 * runner — vitest, node:test, a shell script — without adopting a framework.
 */
export function toEvalCasesModule(exp: EvalExport): string {
  return `// Generated by sift from theme ${exp.themeId}: ${exp.label}
// ${exp.memberCount} traces matched this theme (facet: ${exp.facet}, state: ${exp.state}).

export const theme = ${JSON.stringify(
    { id: exp.themeId, facet: exp.facet, label: exp.label, description: exp.description, state: exp.state },
    null,
    2,
  )};

export const scorerPrompt = ${JSON.stringify(exp.scorerPrompt)};

export const cases = ${JSON.stringify(exp.cases, null, 2)};

export default { theme, scorerPrompt, cases };
`;
}

/** One self-contained case per line, for streaming eval harnesses. */
export function toJsonl(exp: EvalExport): string {
  return exp.cases
    .map((c) => JSON.stringify({ ...c, facet: exp.facet, scorerPrompt: exp.scorerPrompt }))
    .join("\n")
    .concat(exp.cases.length ? "\n" : "");
}

export function toJson(exp: EvalExport): string {
  return `${JSON.stringify(exp, null, 2)}\n`;
}

export const EXPORT_FORMATS = ["mastra-scorer", "cases", "jsonl", "json"] as const;
export type ExportFormat = (typeof EXPORT_FORMATS)[number];

export function renderExport(exp: EvalExport, format: ExportFormat): string {
  switch (format) {
    case "mastra-scorer":
      return toMastraScorerModule(exp);
    case "cases":
      return toEvalCasesModule(exp);
    case "jsonl":
      return toJsonl(exp);
    case "json":
      return toJson(exp);
  }
}
